set -euo pipefail

PDB_NAME="FREEPDB1"

REQUESTED_CHARACTERSET="${1:-}"

if [ -n "$REQUESTED_CHARACTERSET" ]; then
  REQUESTED_CHARACTERSET="${REQUESTED_CHARACTERSET^^}"
fi

if [ -n "$REQUESTED_CHARACTERSET" ]; then
  CHARACTERSET_PATTERN='^[A-Z][A-Z0-9_$#]*$'

  if [[ ! "$REQUESTED_CHARACTERSET" =~ $CHARACTERSET_PATTERN ]]; then
    echo "ERROR: invalid ORACLE_CHARACTERSET value: $REQUESTED_CHARACTERSET" >&2
    exit 1
  fi
fi

"${ORACLE_HOME}/bin/sqlplus" -s / as sysdba <<SQL
WHENEVER SQLERROR EXIT SQL.SQLCODE
SET HEADING OFF FEEDBACK OFF PAGESIZE 0 VERIFY OFF ECHO OFF

DECLARE
  l_open_mode VARCHAR2(30);
BEGIN
  SELECT open_mode
    INTO l_open_mode
    FROM v\$pdbs
   WHERE name = '${PDB_NAME}';

  IF l_open_mode <> 'READ WRITE' THEN
    EXECUTE IMMEDIATE
      'ALTER PLUGGABLE DATABASE "${PDB_NAME}" OPEN READ WRITE FORCE';
  END IF;

  EXECUTE IMMEDIATE 'ALTER PLUGGABLE DATABASE "${PDB_NAME}" SAVE STATE';
END;
/

ALTER SYSTEM REGISTER;
EXIT;
SQL

if [ -n "$REQUESTED_CHARACTERSET" ]; then
  CURRENT_CHARACTERSET="$(${ORACLE_HOME}/bin/sqlplus -s / as sysdba <<SQL
WHENEVER SQLERROR EXIT SQL.SQLCODE
SET HEADING OFF FEEDBACK OFF PAGESIZE 0 VERIFY OFF ECHO OFF
ALTER SESSION SET CONTAINER = "${PDB_NAME}";
SELECT value FROM nls_database_parameters WHERE parameter = 'NLS_CHARACTERSET';
EXIT;
SQL
)"
  CURRENT_CHARACTERSET="$(printf '%s\n' "$CURRENT_CHARACTERSET" | awk 'NF { print toupper($1); exit }')"

  if [ "$CURRENT_CHARACTERSET" != "$REQUESTED_CHARACTERSET" ]; then
    echo "Converting ${PDB_NAME} character set to ${REQUESTED_CHARACTERSET}."
    "${ORACLE_HOME}/bin/sqlplus" -s / as sysdba <<SQL
WHENEVER SQLERROR EXIT SQL.SQLCODE
SET HEADING OFF FEEDBACK OFF PAGESIZE 0 VERIFY OFF ECHO OFF
ALTER PLUGGABLE DATABASE "${PDB_NAME}" CLOSE IMMEDIATE;
ALTER PLUGGABLE DATABASE "${PDB_NAME}" OPEN READ WRITE RESTRICTED;
ALTER SESSION SET CONTAINER = "${PDB_NAME}";
ALTER PLUGGABLE DATABASE CHARACTER SET INTERNAL_USE INTERNAL_CONVERT ${REQUESTED_CHARACTERSET};
ALTER SESSION SET CONTAINER = CDB\$ROOT;
ALTER PLUGGABLE DATABASE "${PDB_NAME}" CLOSE IMMEDIATE;
ALTER PLUGGABLE DATABASE "${PDB_NAME}" OPEN READ WRITE;
ALTER PLUGGABLE DATABASE "${PDB_NAME}" SAVE STATE;
ALTER SYSTEM REGISTER;
EXIT;
SQL
  fi
fi
